const assert = require('assert');
const S = require('../savings-engine.js');
assert.strictEqual(S.VERSION, '2026.08.20-v2');
const prefs = S.validatePreferences({k401:50,hsa:0,roth:25,brokerage:25,cash:0});
assert.strictEqual(prefs.ready,true);
assert.strictEqual(S.validatePreferences({k401:60,hsa:0,roth:25,brokerage:25,cash:0}).ready,false);
assert.strictEqual(S.emergencyTarget({monthlyEssentials:3000,months:3}),9000);
const limits=S.accountLimits({taxYear:2026,age:22,filingStatus:'single',magi:70000,hsaCoverage:'none'});
assert.strictEqual(limits.k401,24500);
assert.strictEqual(limits.roth,7500);
assert.strictEqual(limits.hsa,0);
const alloc=S.allocate({amount:20000,preferences:{k401:50,hsa:0,roth:25,brokerage:25,cash:0},limits,eligibility:{k401:true,hsa:false,roth:true}});
assert.strictEqual(alloc.ready,true);
assert.strictEqual(Object.values(alloc.allocations).reduce((a,b)=>a+b,0),20000);
const rates=S.validateContributionRates({k401:50,hsa:100,roth:50,brokerage:25});
assert.strictEqual(rates.ready,true);
assert.strictEqual(S.validateContributionRates({k401:101,hsa:0,roth:0,brokerage:0}).ready,false);
const dynamic=S.allocatePostTax({amount:20000,contributionRates:rates.rates,limits:{hsa:4400,roth:7500,brokerage:Infinity},eligibility:{hsa:true,roth:true}});
assert.strictEqual(dynamic.ready,true);
assert.strictEqual(dynamic.maxima.hsa,4400);
assert.strictEqual(dynamic.allocations.hsa,4400);
assert.strictEqual(dynamic.maxima.roth,7500);
assert.strictEqual(dynamic.allocations.roth,3750);
assert.strictEqual(dynamic.maxima.brokerage,11850);
assert.strictEqual(dynamic.allocations.brokerage,2962.5);
assert.strictEqual(dynamic.allocations.cash,8887.5);
assert.strictEqual(Object.values(dynamic.allocations).reduce((a,b)=>a+b,0),20000,'post-tax allocation must preserve every dollar');
console.log('PASS test-savings-engine');
